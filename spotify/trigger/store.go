// editorialPrefix starts the IDs of Spotify-owned editorial playlists, which nobody else can add to
const editorialPrefix = "37i9dQZF1"

// playlistIDRegex matches a Spotify playlist ID: 22 base-62 characters
var playlistIDRegex = regexp.MustCompile(`^[0-9A-Za-z]{22}$`)

// playlistLinkRegex extracts the ID from a playlist link or URI, e.g.
// https://open.spotify.com/playlist/<id>?si=..., open.spotify.com/intl-fr/playlist/<id>, or spotify:playlist:<id>
var playlistLinkRegex = regexp.MustCompile(`(?:/playlist/|^spotify:playlist:)([0-9A-Za-z]+)`)

// Header is written at the top of the tags file on every save.
// Keep the frame aligned if the wording changes.
const Header = `# ╔══════════════════════════════════════╗
# ║     AUTOGENERATED - DO NOT EDIT      ║
# ╠══════════════════════════════════════╣
# ║ Use /tag in Discord.                 ║
# ║ - Comments are erased on save.       ║
# ║ - Edits while the bot runs are lost. ║
# ╚══════════════════════════════════════╝
`

// storeFile is the on-disk format of the store: playlists, each with the tags that add to it
type storeFile struct {
	Playlists []storePlaylist `yaml:"playlists"`
}

// storePlaylist is a playlist in the tags file
type storePlaylist struct {
	Name string   `yaml:"name,omitempty"` // Cosmetic, for reading the file; the bot keys on the ID
	ID   string   `yaml:"id"`
	Tags []string `yaml:"tags"`
}

// jsonStoreFile is the earlier JSON format: tag name to playlist ID
type jsonStoreFile struct {
	Tags map[string]string `json:"tags"`
}

// legacyStoreFile is the first JSON format, with a list of playlists per tag
type legacyStoreFile struct {
	Tags map[string][]string `json:"tags"`
}

// Store holds the trigger configuration and persists tag changes to a YAML file.
// Reads are lock-free; writes are serialized and replace the whole configuration.
type Store struct {
	path   string
	mu     sync.Mutex // Serializes writes
	config atomic.Pointer[Config]
	names  atomic.Pointer[map[string]string] // Tagged playlists' IDs to their names on Spotify

	legacy    string // JSON file the tags were converted from, moved aside on the next successful save
	backup    string // Where legacy was moved
	backupErr error  // Why legacy couldn't be moved aside (or the move flushed) on the last save
}

// OpenResult describes what OpenStore did besides loading the tags
type OpenResult struct {
	Created    bool                // No tags file existed, so it was created from the seed
	Converted  bool                // The tags were converted from the JSON file of earlier versions
	Dropped    map[string][]string // Tags converted from several playlists to one, and the playlists they lost
	Backup     string              // Where the JSON file was moved: after converting it, or if it was left over from an interrupted conversion
	YAMLBackup string              // Where the YAML file was moved before converting a newer JSON file, e.g. after a rollback
	SaveErr    error               // Converting the JSON file worked but saving the YAML file didn't; it's retried on the next change
	BackupErr  error               // The YAML file is in use, but the JSON file couldn't be moved aside (retried on the next change) or the move flushed
}

// BackupSuffix is added to the path of a tags file to back it up: the JSON file once it's converted
// to YAML, and the YAML file if a newer JSON file replaces it. If that backup already exists
// (e.g. after a rollback and a second upgrade), a timestamp is added too.
const BackupSuffix = ".bak"

// StorePath returns the YAML file to use for SPOTIFY_TAGS_FILE: path itself or, for a .json
// path set for an earlier version, the .yaml file next to it, so the JSON file is converted
func StorePath(path string) string {
	if strings.EqualFold(filepath.Ext(path), ".json") {
		return strings.TrimSuffix(path, filepath.Ext(path)) + ".yaml"
	}
	return path
}

// LegacyPath returns where earlier versions kept the tags, given the YAML file's path:
// the same path with a .json extension, e.g. /data/playlist-tags.json for /data/playlist-tags.yaml
func LegacyPath(path string) string {
	return strings.TrimSuffix(path, filepath.Ext(path)) + ".json"
}

// idRunRegex matches what may be a playlist ID: a run of at least 22 base-62 characters
var idRunRegex = regexp.MustCompile(`[0-9A-Za-z]{22,}`)

// redactIDs shortens anything that looks like a playlist ID in err's message. Errors about
// the tags file and the seed are logged, and IDs can end up anywhere in them (e.g. an ID
// listed as a tag, or used as a key), so they're redacted wholesale rather than one by one.
func redactIDs(err error) error {
	return log.RedactMatches(err, idRunRegex)
}

// OpenStore loads the tags saved in the YAML file at StorePath(path), using settings for everything
// else (settings' own tags are ignored). The JSON file of earlier versions (see LegacyPath) is
// converted to YAML and moved aside with BackupSuffix if the YAML file doesn't exist yet, or if the
// JSON file is newer, e.g. after a rollback to an older version; the YAML file is backed up first then.
// A JSON file older than the YAML file is left over from an interrupted conversion, so it's just moved aside.
// If neither file exists, the YAML file is created from seed, the tags in SPOTIFY_PLAYLIST_TRIGGERS.
// Tags with several playlists, in the oldest JSON format or the seed, are converted with ToTags.
// Anything that looks like a playlist ID is shortened in the errors, since they're logged.
func OpenStore(path string, settings *Config, seed map[string][]string) (*Store, OpenResult, error) {
	s, result, err := openStore(StorePath(path), settings, seed)
	result.SaveErr = redactIDs(result.SaveErr)
	result.BackupErr = redactIDs(result.BackupErr)
	return s, result, redactIDs(err)
}

// openStore is OpenStore without redacting errors
func openStore(path string, settings *Config, seed map[string][]string) (*Store, OpenResult, error) {
	var result OpenResult
	if settings == nil {
		return nil, result, fmt.Errorf("settings are nil")
	}
	s := &Store{path: path}

	legacyPath := LegacyPath(path)
	info, err := os.Stat(path)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return nil, result, fmt.Errorf("failed to read %s: %w", path, err)
	}
	legacyInfo, legacyErr := os.Stat(legacyPath)
	if legacyErr != nil && !errors.Is(legacyErr, os.ErrNotExist) {
		return nil, result, fmt.Errorf("failed to read %s: %w", legacyPath, legacyErr)
	}
	exists, legacyExists := err == nil, legacyErr == nil

	if legacyExists && (!exists || legacyInfo.ModTime().After(info.ModTime())) {
		return s.convert(settings, legacyPath, exists)
	}
	if exists {
		data, err := os.ReadFile(path)
		if err != nil {
			return nil, result, fmt.Errorf("failed to read %s: %w", path, err)
		}
		tags, names, err := parseStoreFile(data)
		if err != nil {
			return nil, result, fmt.Errorf("invalid tags in %s: %w", path, err)
		}
		if err := s.init(settings, tags, names); err != nil {
			return nil, result, fmt.Errorf("invalid tags in %s: %w", path, err)
		}
		if legacyExists {
			// Left over from a conversion interrupted between saving the YAML file and moving the JSON file aside
			s.legacy = legacyPath
			result.BackupErr = s.backupLegacy()
			result.Backup = s.backup
		}
		return s, result, nil
	}

	seed, err = NormalizePlaylists(seed)
	if err != nil {
		return nil, result, fmt.Errorf("invalid tags to import: %w", err)
	}
	var tags map[string]string
	tags, result.Dropped = ToTags(seed, settings.DefaultPlaylistID)
	if err := s.init(settings, tags, nil); err != nil {
		return nil, OpenResult{}, err
	}
	if err := s.save(tags, nil); err != nil {
		return nil, OpenResult{}, err
	}
	result.Created = true
	return s, result, nil
}

// convert loads the tags from the JSON file of earlier versions and saves them as YAML.
// If replace is true, the YAML file exists but is older than the JSON file, which an older version
// of the bot changed after a rollback, so the YAML file is backed up first, keeping its playlist names.
func (s *Store) convert(settings *Config, legacyPath string, replace bool) (*Store, OpenResult, error) {
	var result OpenResult
	data, err := os.ReadFile(legacyPath)
	if err != nil {
		return nil, result, fmt.Errorf("failed to read %s: %w", legacyPath, err)
	}
	tags, dropped, err := parseJSONStoreFile(data, settings.DefaultPlaylistID)
	if err != nil {
		return nil, result, fmt.Errorf("invalid tags in %s: %w", legacyPath, err)
	}
	var names map[string]string
	if replace {
		// Names are cosmetic, so an invalid YAML file just doesn't provide any
		if data, err := os.ReadFile(s.path); err == nil {
			_, names, _ = parseStoreFile(data)
		}
	}
	if err := s.init(settings, tags, names); err != nil {
		return nil, result, fmt.Errorf("failed to convert %s: %w", legacyPath, err)
	}
	if replace {
		result.YAMLBackup, err = backupFile(s.path)
		if result.YAMLBackup == "" {
			return nil, result, fmt.Errorf("failed to back up %s before converting the newer %s: %w", s.path, legacyPath, err)
		}
		result.BackupErr = err // Backed up, but the backup may not be flushed yet
	}
	result.Converted = true
	result.Dropped = dropped

	// The converted tags work even if they can't be saved yet; the JSON file stays until they are
	s.legacy = legacyPath
	if result.SaveErr = s.save(tags, *s.names.Load()); result.SaveErr == nil {
		result.BackupErr = errors.Join(result.BackupErr, s.backupErr)
	}
	result.Backup = s.backup
	return s, result, nil
}

// parseStoreFile reads the YAML tags file into tag names to playlist IDs, and playlist IDs to names.
// Each playlist must be listed once with at least one tag, and each tag must be under one playlist.
// Errors only show the start of playlist IDs, since they're logged.
func parseStoreFile(data []byte) (tags, names map[string]string, err error) {
	var file storeFile
	decoder := yaml.NewDecoder(bytes.NewReader(data))
	decoder.KnownFields(true) // Catch typos in hand edits instead of silently dropping tags
	if err := decoder.Decode(&file); err != nil && !errors.Is(err, io.EOF) {
		return nil, nil, fmt.Errorf("failed to parse YAML: %w", err)
	}
	tags = make(map[string]string)
	names = make(map[string]string)
	for i, playlist := range file.Playlists {
		id, err := ExtractPlaylistID(playlist.ID)
		if err != nil {
			return nil, nil, fmt.Errorf("playlist #%d: %q isn't a valid Spotify playlist ID or link", i+1, log.RedactID(playlist.ID))
		}
		if _, ok := names[id]; ok {
			return nil, nil, fmt.Errorf("playlist %s is listed more than once; list all its tags under one entry", log.RedactID(id))
		}
		names[id] = playlist.Name
		if len(playlist.Tags) == 0 {
			return nil, nil, fmt.Errorf("playlist %s has no tags; add one or delete the playlist", log.RedactID(id))
		}
		for _, name := range playlist.Tags {
			if err := ValidateName(name); err != nil {
				return nil, nil, fmt.Errorf("playlist %s: %w", log.RedactID(id), err)
			}
			if previous, ok := tags[name]; ok {
				if previous == id {
					return nil, nil, fmt.Errorf("tag %q is listed twice under playlist %s", name, log.RedactID(id))
				}
				return nil, nil, fmt.Errorf("tag %q is listed under more than one playlist, but a tag adds to one playlist only", name)
			}
			tags[name] = id
		}
	}
	maps.DeleteFunc(names, func(_, name string) bool { return name == "" })
	return tags, names, nil
}

// parseJSONStoreFile reads the JSON tags file of earlier versions, in either format: one playlist
// per tag, or a list of playlists per tag, which is converted with ToTags
func parseJSONStoreFile(data []byte, defaultPlaylistID string) (tags map[string]string, dropped map[string][]string, err error) {
	var file jsonStoreFile
	if err := json.Unmarshal(data, &file); err == nil {
		tags, err := normalizeTags(file.Tags)
		return tags, nil, err
	}
	var legacy legacyStoreFile
	if err := json.Unmarshal(data, &legacy); err != nil {
		return nil, nil, fmt.Errorf("failed to parse JSON: %w", err)
	}
	playlists, err := NormalizePlaylists(legacy.Tags)
	if err != nil {
		return nil, nil, err
	}
	tags, dropped = ToTags(playlists, defaultPlaylistID)
	return tags, dropped, nil
}

// init sets the store's initial tags and playlist names
func (s *Store) init(settings *Config, tags, names map[string]string) error {
	config, err := settings.withTags(tags)
	if err != nil {
		return err
	}
	names = taggedNames(names, tags)
	s.config.Store(config)
	s.names.Store(&names)
	return nil
}

// normalizeTags validates tag names and converts playlist links to bare IDs,
// so stored IDs always match what the commands extract
func normalizeTags(tags map[string]string) (map[string]string, error) {
	out := make(map[string]string, len(tags))
	for name, raw := range tags {
		if err := ValidateName(name); err != nil {
			return nil, err
		}
		id, err := ExtractPlaylistID(raw)
		if err != nil {
			return nil, fmt.Errorf("tag %q: %w", name, err)
		}
		out[name] = id
	}
	return out, nil
}

// NormalizePlaylists is normalizeTags for several playlists per tag, as in SPOTIFY_PLAYLIST_TRIGGERS.
// Tags without playlists are dropped.
func NormalizePlaylists(playlists map[string][]string) (map[string][]string, error) {
	out := make(map[string][]string, len(playlists))
	for name, ids := range playlists {
		if err := ValidateName(name); err != nil {
			return nil, redactIDs(err)
		}
		for _, raw := range ids {
			id, err := ExtractPlaylistID(raw)
			if err != nil {
				return nil, redactIDs(fmt.Errorf("tag %q: %w", name, err))
			}
			out[name] = appendUnique(out[name], id)
		}
	}
	return out, nil
}

// Config returns the current trigger configuration. It must not be modified.
func (s *Store) Config() *Config {
	return s.config.Load()
}

// PlaylistName returns the saved name of a tagged playlist, or "" if it's unknown
func (s *Store) PlaylistName(id string) string {
	return (*s.names.Load())[id]
}

// SetPlaylistName saves the name of a tagged playlist, as shown on Spotify.
// Names are only kept for playlists with tags, so other playlists are ignored, as are empty names.
func (s *Store) SetPlaylistName(id, name string) error {
	if name == "" {
		return nil
	}

	s.mu.Lock()
	defer s.mu.Unlock()

	current := s.Config()
	names := *s.names.Load()
	if names[id] == name || !slices.Contains(slices.Collect(maps.Values(current.Tags)), id) {
		return nil
	}
	names = maps.Clone(names)
	names[id] = name
	if err := s.save(current.Tags, names); err != nil {
		return err
	}
	s.names.Store(&names)
	return nil
}

// Add creates a tag pointing to a playlist. If the tag already exists, it's left
// unchanged and its playlist is returned as existing.
func (s *Store) Add(name, playlistID string) (existing string, err error) {
	return s.set(name, playlistID, false)
}

// Set points a tag to a playlist, creating the tag if needed.
// It returns the playlist the tag pointed to before, if any.
func (s *Store) Set(name, playlistID string) (previous string, err error) {
	return s.set(name, playlistID, true)
}

// set creates a tag, or replaces its playlist if replace is true, and returns its previous playlist
func (s *Store) set(name, playlistID string, replace bool) (previous string, err error) {
	if err := ValidateName(name); err != nil {
		return "", err
	}
	if !playlistIDRegex.MatchString(playlistID) {
		return "", fmt.Errorf("invalid playlist ID %q", playlistID)
	}

	s.mu.Lock()
	defer s.mu.Unlock()

	current := s.Config()
	previous = current.Tags[name]
	if previous == playlistID || (previous != "" && !replace) {
		return previous, nil
	}
	tags := maps.Clone(current.Tags)
	tags[name] = playlistID
	return previous, s.update(current, tags)
}

// AliasSkip is why AddAliases left a name out
type AliasSkip int

const (
	AliasExists   AliasSkip = iota + 1 // The tag already adds to the playlist
	AliasTaken                         // The tag adds to another playlist, which AddAliases never changes
	AliasInvalid                       // The name isn't a valid tag name
	AliasReserved                      // The name is DefaultName
)

// SkippedAlias is a name AddAliases left out
type SkippedAlias struct {
	Name       string
	Reason     AliasSkip
	PlaylistID string // For AliasTaken, the playlist the tag adds to
}

// AliasResult describes what AddAliases did
type AliasResult struct {
	PlaylistID string         // Playlist the existing tag adds to
	Added      []string       // Tags created, in the order given
	Skipped    []SkippedAlias // Names left out, in the order given
}

// AddAliases creates tags pointing to the same playlist as an existing tag, or as the default playlist
// for DefaultName. Names that are already tags or aren't valid (see ValidateName) are skipped; repeats
// are ignored. Names must already be normalized: lowercase, without the prefix.
// All the new tags are saved in one write, so either all of them are added or none are.
func (s *Store) AddAliases(existing string, names []string) (AliasResult, error) {
	s.mu.Lock()
	defer s.mu.Unlock()

	current := s.Config()
	var result AliasResult
	if existing == DefaultName {
		result.PlaylistID = current.DefaultPlaylistID
	} else if id, ok := current.Tags[existing]; ok {
		result.PlaylistID = id
	} else {
		return result, fmt.Errorf("there's no %s%s tag", current.Prefix, existing)
	}

	tags := maps.Clone(current.Tags)
	seen := make(map[string]bool, len(names))
	for _, name := range names {
		if seen[name] {
			continue
		}
		seen[name] = true
		skip := SkippedAlias{Name: name}
		switch id, exists := tags[name]; {
		case name == DefaultName:
			skip.Reason = AliasReserved
		case ValidateName(name) != nil:
			skip.Reason = AliasInvalid
		case id == result.PlaylistID:
			skip.Reason = AliasExists
		case exists:
			skip.Reason, skip.PlaylistID = AliasTaken, id
		default:
			tags[name] = result.PlaylistID
			result.Added = append(result.Added, name)
			continue
		}
		result.Skipped = append(result.Skipped, skip)
	}
	if len(result.Added) == 0 {
		return result, nil
	}
	if err := s.update(current, tags); err != nil {
		return AliasResult{}, err
	}
	return result, nil
}

// Remove deletes a tag and returns the playlist it pointed to
func (s *Store) Remove(name string) (previous string, err error) {
	if err := ValidateName(name); err != nil {
		return "", err
	}

	s.mu.Lock()
	defer s.mu.Unlock()

	current := s.Config()
	previous, ok := current.Tags[name]
	if !ok {
		return "", fmt.Errorf("there's no %s%s tag", current.Prefix, name)
	}
	tags := maps.Clone(current.Tags)
	delete(tags, name)
	return previous, s.update(current, tags)
}

// update saves the new tags and makes them current, forgetting the names of playlists
// left without tags. The caller must hold s.mu.
func (s *Store) update(current *Config, tags map[string]string) error {
	config, err := current.withTags(tags)
	if err != nil {
		return err
	}
	names := taggedNames(*s.names.Load(), tags)
	if err := s.save(tags, names); err != nil {
		return err
	}
	s.config.Store(config)
	s.names.Store(&names)
	return nil
}

// taggedNames returns the names of the playlists that have tags
func taggedNames(names, tags map[string]string) map[string]string {
	out := make(map[string]string)
	for _, id := range tags {
		if name := names[id]; name != "" {
			out[id] = name
		}
	}
	return out
}

// encode formats the tags as YAML, grouped by playlist. The output is deterministic so diffs stay clean:
// playlists are sorted by name, then ID, and each playlist's tags are sorted.
func encode(tags, names map[string]string) ([]byte, error) {
	byPlaylist := make(map[string][]string)
	for _, name := range slices.Sorted(maps.Keys(tags)) {
		id := tags[name]
		byPlaylist[id] = append(byPlaylist[id], name)
	}
	file := storeFile{Playlists: []storePlaylist{}}
	for id, tagNames := range byPlaylist {
		file.Playlists = append(file.Playlists, storePlaylist{Name: names[id], ID: id, Tags: tagNames})
	}
	slices.SortFunc(file.Playlists, func(a, b storePlaylist) int {
		return cmp.Or(strings.Compare(a.Name, b.Name), strings.Compare(a.ID, b.ID))
	})

	buf := bytes.NewBufferString(Header)
	encoder := yaml.NewEncoder(buf)
	encoder.SetIndent(2)
	if err := encoder.Encode(file); err != nil {
		return nil, err
	}
	if err := encoder.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// save writes the tags to disk, then moves aside the JSON file they were converted from, if that's
// still pending. The YAML file is in use once it's written, so failing to move the JSON file isn't
// a failed save: it's recorded in s.backupErr and retried on the next save.
func (s *Store) save(tags, names map[string]string) error {
	if err := s.write(tags, names); err != nil {
		return err
	}
	s.backupErr = nil
	if s.legacy != "" {
		s.backupErr = s.backupLegacy()
	}
	return nil
}

// write writes the tags to disk atomically, so a crash never leaves a half-written file
func (s *Store) write(tags, names map[string]string) error {
	data, err := encode(tags, names)
	if err != nil {
		return fmt.Errorf("failed to encode tags: %w", err)
	}
	dir := filepath.Dir(s.path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("failed to create %s: %w", dir, err)
	}
	tmp, err := os.CreateTemp(dir, filepath.Base(s.path)+".tmp-*")
	if err != nil {
		return fmt.Errorf("failed to save tags: %w", err)
	}
	defer os.Remove(tmp.Name()) // No-op after a successful rename
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return fmt.Errorf("failed to save tags: %w", err)
	}
	// Flush the data before the rename, so the rename can't reach the disk first
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		return fmt.Errorf("failed to save tags: %w", err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("failed to save tags: %w", err)
	}
	if err := os.Rename(tmp.Name(), s.path); err != nil {
		return fmt.Errorf("failed to save tags: %w", err)
	}
	// Flush the rename itself
	if err := syncDir(dir); err != nil {
		return fmt.Errorf("failed to save tags: %w", err)
	}
	return nil
}

// backupLegacy moves the JSON file the tags were converted from aside once the YAML file is saved,
// so it's clear which file is in use, while keeping playlists dropped by the conversion and what's
// needed to roll back to an older version of the bot. Once it's moved, it's no longer pending,
// even if flushing the move failed.
func (s *Store) backupLegacy() error {
	path, err := backupFile(s.legacy)
	if path != "" {
		s.legacy = ""
		s.backup = path
	}
	return err
}

// backupFile renames path by adding BackupSuffix, along with a timestamp if that backup already
// exists (e.g. from an earlier upgrade, before a rollback), so backups are never overwritten.
// It returns the backup's path once the rename succeeded, along with any error flushing it.
func backupFile(path string) (string, error) {
	backup := path + BackupSuffix
	if _, err := os.Lstat(backup); !errors.Is(err, os.ErrNotExist) {
		backup = fmt.Sprintf("%s.%s%s", path, time.Now().UTC().Format("20060102T150405.000000000Z"), BackupSuffix)
	}
	if err := os.Rename(path, backup); err != nil {
		return "", fmt.Errorf("failed to back up %s: %w", path, err)
	}
	if err := syncDir(filepath.Dir(backup)); err != nil {
		return backup, fmt.Errorf("backed up %s to %s but failed to flush it to disk: %w", path, backup, err)
	}
	return backup, nil
}

// syncDir flushes a directory's entries to disk
func syncDir(dir string) error {
	d, err := os.Open(dir)
	if err != nil {
		return err
	}
	defer d.Close()
	return d.Sync()
}

// withTags returns a copy of c with different tags
func (c *Config) withTags(tags map[string]string) (*Config, error) {
	return New(c.Prefix, c.DefaultPlaylistID, tags, c.ReplyUnknown)
}

// ValidateName checks that a tag name (without the prefix) is lowercase, valid, at most MaxNameLength
// characters, and not reserved
func ValidateName(name string) error {
	if !nameRegex.MatchString(name) || name != strings.ToLower(name) {
		return fmt.Errorf("invalid tag name %q: use letters and numbers, optionally joined by a single - or _", name)
	}
	if utf8.RuneCountInString(name) > MaxNameLength {
		return fmt.Errorf("tag name %q is too long: use at most %d characters", name, MaxNameLength)
	}
	if name == DefaultName {
		return fmt.Errorf("%q is reserved for the default playlist", DefaultName)
	}
	return nil
}

// ParsePlaylistID extracts the playlist ID from a Spotify playlist link, URI, or bare ID.
// Spotify-owned editorial playlists are rejected, since nobody else can add to them.
func ParsePlaylistID(input string) (string, error) {
	id, err := ExtractPlaylistID(input)
	if err != nil {
		return "", err
	}
	if strings.HasPrefix(id, editorialPrefix) {
		return "", fmt.Errorf("that's a Spotify-made playlist, which nobody can add songs to; copy its songs into a collaborative playlist instead")
	}
	return id, nil
}

// ExtractPlaylistID extracts the playlist ID from a Spotify playlist link, URI, or bare ID
func ExtractPlaylistID(input string) (string, error) {
	input = strings.TrimSpace(input)
	id := input
	if m := playlistLinkRegex.FindStringSubmatch(input); m != nil {
		id = m[1]
	} else if strings.ContainsAny(input, "/:") {
		return "", fmt.Errorf("that isn't a Spotify playlist link")
	}
	if !playlistIDRegex.MatchString(id) {
		return "", fmt.Errorf("%q isn't a valid Spotify playlist ID", id)
	}
	return id, nil
}
